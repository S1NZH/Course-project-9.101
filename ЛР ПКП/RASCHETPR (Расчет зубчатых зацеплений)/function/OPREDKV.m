function [ KFV ] = OPREDKV( FT,Z1,VZAC )
%Подпрограмма определения коэффициента Kfv
%
global M BW BETTA  X EY D2 ZV1 ZV2 KA DELTAF G0
global V DW1 ITOCH U AW NDVSSR SIGMAHLIMB1 EALFA
%
YALFA=0; 
CV1=0.32; CV2=0.34; CV4=0.90; CV5=0.47; CV6=0.47; CV7=0.75;
if EY>2, CV2=0.32; CV4=0.32; CV5=0.32; CV6=0.32; end
if (EY>1)&&(EY<=1.5), CV7=0.75; end
if (EY>1.5)&&(EY<2.5) 
    CV7=pi*(EY-1.96)/1.12; 
    CV7=0.125*sin(CV7)+0.875; 
end
if EY>=2.5, CV7=1; end
if BETTA==0, KOEFF=1; end
if BETTA~=0, KOEFF=1.4; end
ASD=V*Z1/1000;
if ASD<=KOEFF
WFT=DELTAF*G0*VZAC*sqrt(AW/U);
NUJH=WFT*BW/(FT*KA);
KFV=abs(1.+NUJH);
return
end
MRED=3.25E-9*D2^2/((U^2)+1);
C=0.05139+(0.1425/ZV1)+(0.1860/ZV2)-0.01*X(1)-(0.1027*X(1)/ZV1)+...
0.00455*X(2)+(0.3762*X(2)/ZV2)+0.00734*(X(1)^2)-0.00054*X(2)^2;
C=1/C;
CGAMMA=C*(0.75*EALFA+0.25);
NE1=sqrt(CGAMMA*BW/MRED);
NE1=30*NE1/(Z1);
OTNOSH=NDVSSR/NE1;
%
[FPB]=OPREDFB(ITOCH,M,DW1);
%
YALFA=0.075*FPB;
FPBEFF=FPB-YALFA;
BP=C*FPBEFF*BW/(FT*KA); 
%
[FF]=OPREDFF(ITOCH,M,DW1);
%
BF=C*(FF-YALFA)*BW/(FT*KA);
CA=SIGMAHLIMB1/97;
CA=((CA-18.445)^2)/18;
CA=1.5+CA;
BK=abs(1-abs(C*CA*BW/FT)); 
%
if OTNOSH<0.85
WFT=DELTAF*G0*VZAC*sqrt(AW/U);
NUJH=WFT*BW/(FT*KA);
KFV=1.+NUJH;
KFV=abs(KFV);
return
end
if (OTNOSH>=0.85)&&(OTNOSH<=1.15)
KFV=abs(1+CV1*BP+CV2*BF+CV4*BK);
return
end
if (OTNOSH>1.15)&&(OTNOSH<1.5)
KV115=1+CV1*BP+CV2*BF+CV4*BK;
KV15=CV5*BP+CV6*BF+CV7;
KFV=(KV115-KV15)/0.35;
KFV=KFV*(1.5-OTNOSH);
KFV=abs(KV15+KFV);
return
end
if OTNOSH>=1.5
KFV=abs(CV5*BP+CV6*BF+CV7);
return
KFV=abs(KFV);
end
end

