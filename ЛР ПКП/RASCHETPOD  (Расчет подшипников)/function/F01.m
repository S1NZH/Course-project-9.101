      35.3,34.6];
%
if NEQ == 0
    OTN(1)=0.01;
    for I=2:40
        OTN(I)=OTN(I-1)+0.01;
    end
    NEQ=1;
end 
%
for I=2:41      
    if A == OTN(I)
        if TIP == 1, F0=F1(I); end
        if TIP == 2, F0=F2(I); end
	    return
    end  
	if A > OTN(I), continue; end
    if TIP == 1
        F0=(F1(I)-F1(I-1))/(OTN(I)-OTN(I-1));
        F0=F1(I-1)+(F0*(A-OTN(I-1)));
    end
    if TIP == 2
        F0=(F2(I)-F2(I-1))/(OTN(I)-OTN(I-1));
        F0=F2(I-1)+(F0*(A-OTN(I-1)));
    end
    return
end     
end

