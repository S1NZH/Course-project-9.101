%     
NEQ=0;
F1 = [14.7,14.9,15.1,15.3,15.5,15.7,15.9,16.1,16.3,16.5,16.4,...
      16.1,15.9,15.6,15.4,15.2,14.9,14.7,14.4,14.2,14.0,13.7,...
      13.5,13.2,13.0,12.8,12.5,12.3,12.1,11.8,11.6,11.4,11.2,...
      10.9,10.7,10.5,10.3,10.0,9.8,9.6,9.4];
